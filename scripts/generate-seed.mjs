// Generates supabase/seed.sql from the DEMO mock data in src/lib/mock, so the database seed and
// the mock storefront stay identical until Phase 3 switches the catalog to Supabase.
//
//   npm run db:seed:generate
//
// Node 24 loads the mock .ts files directly (type-only imports are stripped).
// IDs are deterministic: md5('ust-demo:<mock id>')::uuid, so re-running produces the same rows.
import { writeFileSync } from "node:fs";

const { DEMO_CATEGORIES } = await import("../src/lib/mock/categories.ts");
const { DEMO_PRODUCTS } = await import("../src/lib/mock/products.ts");
const { DEMO_STORE_SETTINGS } = await import("../src/lib/mock/store-settings.ts");
const { DEMO_TRACTOR_MODELS, DEMO_PRODUCT_FITMENTS } = await import("../src/lib/mock/tractors.ts");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const id = (key) => `md5(${q(`ust-demo:${key}`)})::uuid`;
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const arr = (xs) => (xs.length ? `array[${xs.map(q).join(", ")}]` : "'{}'::text[]");

const catById = new Map(DEMO_CATEGORIES.map((c) => [c.id, c]));
const topSlugOf = (categoryId) => {
  let c = catById.get(categoryId);
  while (c && c.parent_id) c = catById.get(c.parent_id);
  return c?.slug;
};
const productType = (p) => {
  const cat = catById.get(p.category_id);
  const top = topSlugOf(p.category_id);
  if (["engine-oils", "lubricants", "hydraulic-oils"].includes(top)) return "oil";
  if (top === "filters") return "filter";
  if (cat?.slug === "tyres") return "tyre";
  if (top === "hardware-tools") return "tool";
  if (top === "tractor-accessories") return "accessory";
  return "part";
};

const out = [];
out.push(`-- DEMO DATA ONLY. Generated by scripts/generate-seed.mjs from src/lib/mock/ — do not edit by hand.
-- Products, prices, stock and specs are illustrative, not verified business facts.
-- No customers, orders, staff accounts or bank details. Shipping fees are DEMO placeholders.
-- Contact details are the client-approved DEMO values from the designs; confirm before launch.
--
-- Remove all demo catalog data later with the snippet in docs/DATABASE.md ("Removing demo data").

begin;
`);

// Store settings (the row is created by the migration).
const s = DEMO_STORE_SETTINGS;
out.push(`-- Store settings (DEMO contact values; threshold and return period are PLACEHOLDERS)
update public.store_settings set
  business_name = ${q(s.business_name)},
  tagline = ${q(s.tagline)},
  value_statement = ${q(s.value_statement)},
  phone_primary = ${q(s.phone_primary)},
  phone_secondary = ${q(s.phone_secondary)},
  whatsapp_number = ${q(s.whatsapp_number)},
  email = ${q(s.email)},
  address_line = ${q(s.address_line)},
  city = ${q(s.city)},
  province = ${q(s.province)},
  business_hours = ${q(s.business_hours)},
  free_delivery_threshold_paisa = ${s.free_delivery_threshold_paisa ?? "null"},
  return_period_days = ${s.return_period_days ?? "null"},
  guest_checkout_enabled = true,
  cod_enabled = ${s.payment_methods.some((m) => m.id === "cod" && m.enabled)},
  bank_transfer_enabled = ${s.payment_methods.some((m) => m.id === "bank_transfer" && m.enabled)}
where id;
`);

// Delivery methods and DEMO default shipping rates (one nationwide rate per method).
const DEMO_FEES = { cargo_terminal: 500_00, courier: 300_00 };
out.push("-- Delivery methods and DEMO shipping rates (placeholder fees; set real ones in admin)");
s.delivery_methods.forEach((m, i) => {
  out.push(`insert into public.delivery_methods (id, name, description, sort_order)
values (${q(m.id)}, ${q(m.name)}, ${q(m.description)}, ${i + 1})
on conflict (id) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;`);
  out.push(`insert into public.shipping_rates (id, delivery_method_id, fee_paisa)
values (${id(`rate:${m.id}`)}, ${q(m.id)}, ${DEMO_FEES[m.id] ?? 0})
on conflict (id) do update set fee_paisa = excluded.fee_paisa;`);
});
out.push("");

// Categories: parents before children.
out.push("-- Categories");
const ordered = [...DEMO_CATEGORIES].sort((a, b) => (a.parent_id ? 1 : 0) - (b.parent_id ? 1 : 0));
for (const c of ordered) {
  out.push(`insert into public.categories (id, parent_id, slug, name, description, icon, sort_order, is_active)
values (${id(c.id)}, ${c.parent_id ? id(c.parent_id) : "null"}, ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${c.sort_order}, ${c.is_active})
on conflict (id) do update set parent_id = excluded.parent_id, slug = excluded.slug, name = excluded.name,
  description = excluded.description, icon = excluded.icon, sort_order = excluded.sort_order, is_active = excluded.is_active;`);
}
out.push("");

// Tractor makes and models.
out.push("-- Tractor makes and models");
const makes = [...new Set(DEMO_TRACTOR_MODELS.map((m) => m.make))];
makes.forEach((make, i) => {
  out.push(`insert into public.tractor_makes (id, slug, name, sort_order)
values (${id(`make:${make}`)}, ${q(slugify(make))}, ${q(make)}, ${i + 1})
on conflict (id) do update set slug = excluded.slug, name = excluded.name, sort_order = excluded.sort_order;`);
});
DEMO_TRACTOR_MODELS.forEach((m, i) => {
  out.push(`insert into public.tractor_models (id, make_id, slug, name, year_from, year_to, sort_order)
values (${id(m.id)}, ${id(`make:${m.make}`)}, ${q(slugify(m.model))}, ${q(m.model)}, ${m.year_from ?? "null"}, ${m.year_to ?? "null"}, ${i + 1})
on conflict (id) do update set make_id = excluded.make_id, slug = excluded.slug, name = excluded.name,
  year_from = excluded.year_from, year_to = excluded.year_to, sort_order = excluded.sort_order;`);
});
out.push("");

// Products, one default variant each, opening stock through the ledger.
out.push("-- Products (one default variant each). Price: regular = compare-at if present, sale = mock price.");
for (const p of DEMO_PRODUCTS) {
  const regular = p.compare_at_price_paisa ?? p.retail_price_paisa;
  const sale = p.compare_at_price_paisa !== null ? p.retail_price_paisa : null;
  out.push(`insert into public.products (id, slug, name, short_description, description, category_id, product_type,
  oem_part_numbers, specs, origin, status)
values (${id(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.short_description)}, ${q(p.description)}, ${id(p.category_id)},
  ${q(productType(p))}, ${arr(p.oem_ref ? [p.oem_ref] : [])}, ${q(JSON.stringify(p.specs))}::jsonb, ${q(p.origin)}, 'published')
on conflict (id) do update set slug = excluded.slug, name = excluded.name, short_description = excluded.short_description,
  description = excluded.description, category_id = excluded.category_id, product_type = excluded.product_type,
  oem_part_numbers = excluded.oem_part_numbers, specs = excluded.specs, origin = excluded.origin, status = excluded.status;`);
  out.push(`insert into public.product_variants (id, product_id, sku, name, regular_price_paisa, sale_price_paisa, is_default)
values (${id(`variant:${p.id}`)}, ${id(p.id)}, ${q(p.sku)}, 'Default', ${regular}, ${sale ?? "null"}, true)
on conflict (id) do update set sku = excluded.sku, regular_price_paisa = excluded.regular_price_paisa,
  sale_price_paisa = excluded.sale_price_paisa;`);
}
out.push("");

out.push(`-- Opening stock (DEMO). Written to the ledger so inventory always equals the sum of movements.
-- Only applied to variants that have no stock history yet, so re-running the seed is safe.
with opening (variant_id, qty, threshold) as (
  values
${DEMO_PRODUCTS.map((p) => `    (${id(`variant:${p.id}`)}, ${p.stock_qty}, ${p.low_stock_threshold})`).join(",\n")}
), fresh as (
  select o.* from opening o
   where o.qty > 0
     and not exists (select 1 from public.stock_movements m where m.variant_id = o.variant_id)
), updated as (
  update public.inventory i
     set on_hand = i.on_hand + f.qty, low_stock_threshold = f.threshold
    from fresh f
   where i.variant_id = f.variant_id
  returning i.variant_id, f.qty, i.on_hand, i.reserved
)
insert into public.stock_movements (variant_id, movement_type, on_hand_delta, on_hand_after, reserved_after, reason)
select variant_id, 'receive', qty, on_hand, reserved, 'DEMO opening stock' from updated;
`);

out.push("-- Compatibility");
for (const f of DEMO_PRODUCT_FITMENTS) {
  out.push(`insert into public.product_compatibility (product_id, tractor_model_id)
values (${id(f.product_id)}, ${id(f.tractor_model_id)})
on conflict (product_id, tractor_model_id) do nothing;`);
}

out.push("\ncommit;\n");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${DEMO_CATEGORIES.length} categories, ${DEMO_PRODUCTS.length} products, ${DEMO_TRACTOR_MODELS.length} models, ${DEMO_PRODUCT_FITMENTS.length} fitments`);
